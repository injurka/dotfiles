export function getSystemPrompt(profile?: string, customPrompt?: string): string {
  const selected = profile || 'frontend'
  if (selected === 'custom' && customPrompt) {
    return `${customPrompt}\n${defaultSystemPromptSuffix}`
  }
  const basePrompt = profiles[selected]?.prompt || profiles.frontend!.prompt
  return `${basePrompt}\n${defaultSystemPromptSuffix}`
}
