local function canonical(combo)
 local t={} for s in combo:gmatch("[^+]+") do
  local v=s:match("^%s*(.-)%s*$"):upper()
  if v=="CONTROL" then v="CTRL" end
  t[#t+1]=v
 end
 local key=table.remove(t) or ""
 table.sort(t); t[#t+1]=key
 return table.concat(t," + ")
end
local original = hl.bind
hl.bind = function(combo, action, ...)
 local k=canonical(combo)
 -- Bare Super handlers conflict with US/RU switching; raw keycodes could
 -- alias a preserved numeric workspace shortcut.
 if protected[k] or combo:match("code:") or k:match("SUPER_[LR]$") then return end
 return original(combo, action, ...)
end
return function() hl.bind=original end
