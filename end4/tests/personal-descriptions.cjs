const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const base = path.join(__dirname, '../home/.config/quickshell/ii');
const schedule = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(base, 'modules/ii/sidebarRight/calendar/schedule.js'), 'utf8').replace('.pragma library', ''), schedule);
const service = fs.readFileSync(path.join(base, 'services/Agenda.qml'), 'utf8');
const agenda = vm.createContext({Schedule:schedule, data:schedule.initial(), save(next) {
    assert.ok(schedule.valid(next));
    agenda.data = next;
    return true;
}});
vm.runInContext(service.slice(service.indexOf('    function store('), service.indexOf('    function remove(')), agenda);
vm.runInContext(service.slice(service.indexOf('    function move('), service.indexOf('    function restore(')), agenda);
const day = new Date(2026, 9, 19, 12);
assert.ok(agenda.store(day, 'Once', '10:00', '11:00', [], null, false, '#c9aceb', '  Plan\nhttps://meet.example.org/room  '));
assert.equal(agenda.data.events[0].description, 'Plan\nhttps://meet.example.org/room');
let event = schedule.occurrences(agenda.data, day)[0];
assert.equal(event.links[0], 'https://meet.example.org/room');
assert.ok(schedule.descriptionHtml(event, 'Join').includes('href="https://meet.example.org/room"'));
assert.ok(agenda.store(day, 'Once', '10:00', '11:00', [], event, false, '#c9aceb', ''));
assert.equal(agenda.data.events[0].description, '');
agenda.data = schedule.initial();
assert.ok(agenda.store(day, 'Routine', '10:00', '11:00', [1], null, false, '#c9aceb', 'Series description'));
event = schedule.occurrences(agenda.data, day)[0];
assert.ok(agenda.store(day, 'Routine', '10:00', '11:00', [1], event, false, '#c9aceb', 'Today only'));
event = schedule.occurrences(agenda.data, day)[0];
assert.equal(event.description, 'Today only');
assert.equal(schedule.occurrences(agenda.data, new Date(2026,9,26,12))[0].description, 'Series description');
agenda.move(event, 15);
assert.equal(schedule.occurrences(agenda.data, day)[0].description, 'Today only');
assert.ok(agenda.store(day, 'Routine', '10:00', '11:00', [1], event, true, '#c9aceb', 'Updated series'));
assert.equal(schedule.occurrences(agenda.data, new Date(2026,9,26,12))[0].description, 'Updated series');
const exported = JSON.parse(JSON.stringify(agenda.data));
assert.equal(exported.routines[0].description, 'Updated series');
assert.equal(exported.exceptions[event.occurrenceId].description, 'Today only');
assert.ok(schedule.valid({version:1,presetEnabled:false,routines:[],events:[{id:'legacy',title:'Old event',date:'2026-10-19',start:600,end:660}],exceptions:{}}));
const invalid = JSON.parse(JSON.stringify(agenda.data)); invalid.routines[0].description = {};
assert.equal(schedule.valid(invalid), false);
const preset = {format:'ii-agenda-preset',version:1,id:'test',routines:[{id:'call',title:'Call',days:[1],start:'10:00',end:'11:00',description:'Imported notes'}]};
assert.equal(schedule.importPreset(schedule.initial(),preset).routines[0].description,'Imported notes');
console.log('Personal descriptions: create/edit/clear, series and single days, links, moves, export, presets, and legacy data passed');
