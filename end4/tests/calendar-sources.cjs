const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const schedule = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../home/.config/quickshell/ii/modules/ii/sidebarRight/calendar/schedule.js'), 'utf8').replace('.pragma library', ''), schedule);
const day = new Date(2026, 9, 19, 12);
const data = {version: 1, presetEnabled: false, routines: [], exceptions: {}, events: [
    {id: 'personal', date: '2026-10-19', title: 'Personal', start: 600, end: 660}
]};
const work = [{id: 'work', title: 'Meeting', startAt: new Date(2026, 9, 19, 10, 30).toISOString(), endAt: new Date(2026, 9, 19, 11, 30).toISOString()}];
const original = JSON.stringify(data);
assert.equal(schedule.mergedDay(data, day, work, 'personal').length, 1);
assert.equal(schedule.mergedDay(data, day, work, 'work').length, 1);
const all = schedule.mergedDay(data, day, work, 'all');
assert.equal(all.length, 2);
assert.ok(all.every(e => e.lanes === 2 && e.conflict));
assert.equal(all[1].readOnly, true);
assert.equal(all[1].start, 630);
assert.equal(JSON.stringify(data), original);
const overnight = [{id:'night', startAt: new Date(2026,9,18,23).toISOString(), endAt: new Date(2026,9,19,1).toISOString()}];
const night = schedule.mergedDay(data, day, overnight, 'work')[0];
assert.equal(night.start, 0);
assert.equal(night.end, 60);
assert.equal(schedule.mergedDay(data, new Date(2026,9,20), work, 'work').length, 0);
const fullDay = [{id:'all-day', startAt: new Date(2026,9,19).toISOString(), endAt: new Date(2026,9,20).toISOString(), allDay:true}];
assert.equal(schedule.mergedDay(data, day, fullDay, 'work')[0].end, 1440);
console.log('Calendar scopes, merged conflicts, overnight events and input preservation passed');

assert.equal(schedule.compactDescription({description:'  Intro\r\n\r\n\r\n  Agenda\n\n\nNext  '}), 'Intro\n\n  Agenda\n\nNext');
assert.equal(schedule.linkCaption('https://prosebya.ktalk.ru/room', 'Join meeting'), 'Join meeting');
assert.equal(schedule.linkCaption('https://jira.example.org/board?token=hidden', 'Join meeting'), 'jira.example.org');
assert.equal(schedule.isMeetingLink('https://ktalk.ru.evil.example/room'), false);
assert.equal(schedule.isMeetingLink('https://teams.microsoft.com/l/meetup-join/room'), true);
console.log('Description spacing and meeting link captions passed');
const defaults = schedule.windowSize(null, false, 1920, 1080);
assert.equal(defaults.width, 560);
assert.equal(defaults.height, 880);
assert.equal(schedule.windowSize(null, true, 1920, 1080).width, 1040);
const smaller = schedule.windowSize({dayWidth: 100, weekWidth: 200, height: 150}, true, 1920, 1080);
assert.equal(smaller.width, 1040);
assert.equal(smaller.height, 880);
const enlarged = schedule.windowSize({dayWidth: 850, weekWidth: 1500, height: 980}, false, 1920, 1080);
assert.equal(enlarged.width, 850);
assert.equal(enlarged.height, 980);
const tinyScreen = schedule.windowSize({weekWidth: 2200, height: 1800}, true, 800, 600);
assert.equal(tinyScreen.width, 760);
assert.equal(tinyScreen.height, 560);
assert.equal(tinyScreen.minWidth, 760);
assert.equal(tinyScreen.minHeight, 560);
assert.equal(schedule.windowSizes({dayWidth: 'wrong', height: NaN}).height, 880);
console.log('Window defaults, minimum sizes, saved dimensions and screen limits passed');

const richEvent = {description: 'Agenda <script>unsafe</script>\n\nBoard: https://jira.example.org/board?x=1&y=2\nCall: https://team.ktalk.ru/room.', links: ['https://jira.example.org/board?x=1&y=2','https://team.ktalk.ru/room','https://example.org/additional']};
const rich = schedule.descriptionHtml(richEvent, 'Join meeting');
assert.ok(rich.includes('&lt;script&gt;unsafe&lt;/script&gt;'));
assert.ok(rich.includes('<a href="https://jira.example.org/board?x=1&amp;y=2">jira.example.org</a>'));
assert.ok(rich.includes('<a href="https://team.ktalk.ru/room">Join meeting</a>.'));
assert.ok(!rich.includes('<script>'));
assert.ok(!rich.includes('javascript:'));
assert.equal(schedule.extraLinksHtml(richEvent, 'Join meeting'), '<a href="https://example.org/additional">example.org</a>');
const escapedMarkup = schedule.descriptionHtml({description:'<img src="https://example.org/track">',links:[]}, 'Join');
assert.ok(escapedMarkup.includes('&lt;img src=&quot;'));
assert.ok(!escapedMarkup.includes('<img '));
console.log('Formatted descriptions preserve addresses, escape markup and avoid duplicate links');

const resized = schedule.resizedWindow({dayWidth:560,weekWidth:1300,height:880}, false, 900, 950, 1920,1080);
assert.equal(resized.dayWidth,900);
assert.equal(resized.weekWidth,1300);
assert.equal(resized.height,950);
assert.equal(schedule.resizedWindow(null,false,400,900,1920,1080),null);
const clipped = schedule.resizedWindow({weekWidth:1500,height:1000},true,760,560,800,600);
assert.equal(clipped.weekWidth,1500);
assert.equal(clipped.height,1000);
const shortScreen = schedule.resizedWindow({dayWidth:560,height:1000},false,900,660,1920,700);
assert.equal(shortScreen.dayWidth,900);
assert.equal(shortScreen.height,1000);
console.log('Native resize persistence, minimum hints and monitor constraints passed');
const overlapping = [{id:'later',start:840,end:870},{id:'meeting',start:660,end:720},{id:'routine',start:630,end:840}];
const originalOverlapInput = JSON.stringify(overlapping);
const grouped = schedule.overlapGroups(overlapping, true);
assert.equal(grouped.length, 2);
assert.equal(grouped[0].start, 630);
assert.equal(grouped[0].end, 840);
assert.equal(grouped[0].events.length, 2);
assert.equal(grouped[0].overlapping, true);
assert.equal(grouped[1].events[0].id, 'later');
assert.equal(grouped[1].overlapping, false);
assert.equal(JSON.stringify(overlapping), originalOverlapInput);
assert.equal(schedule.overlapGroups(overlapping, false).length, 3);
assert.ok(schedule.overlapGroups(overlapping, false).every(group => !group.overlapping));
const chain = schedule.overlapGroups([{start:540,end:600},{start:570,end:630},{start:615,end:660},{start:660,end:720}], true);
assert.equal(chain.length, 2);
assert.equal(chain[0].events.length, 3);
assert.equal(chain[0].end, 660);
assert.equal(schedule.overlapGroups([], true).length, 0);
console.log('All-mode overlap grouping: nesting, chained overlaps, adjacent boundaries, unchanged sources and independent modes passed');
